#!/usr/bin/env node
/**
 * Derives which permission keys name a **write**, from the server's own permission matrix.
 *
 *   node tools/gen-permissions.mjs           write src/app/core/permissions/permissions.generated.ts
 *   node tools/gen-permissions.mjs --check   fail (exit 1) when the committed file has drifted
 *
 * Why this exists: an Admin's "View as" session is read-only on the server — `ReadOnlyGuard`
 * refuses every non-GET — so the dashboard must hide exactly the actions that would be refused.
 * Guessing from the shape of the key ("anything not ending `.read`") gets `usage.platform` and
 * `usage.school` wrong: both are pure reads, and an Admin viewing as a Managerial user would
 * lose "School usage", which is close to the point of View-as.
 *
 * `permissions.json` already says the truth. Each endpoint declares its method and its
 * permission, so a key is a write exactly when at least one endpoint that declares it is not a
 * GET or a HEAD. This reads that, and a spec re-derives it so the committed file cannot drift.
 *
 * Unlike `gen:api` the output is **committed**: it is a dozen lines, it needs no Java, and it
 * lets `pnpm test` check the derivation without shelling out.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(here, '../../server/src/main/resources/permissions.json');
const TARGET = resolve(here, '../src/app/core/permissions/permissions.generated.ts');

/** Methods that change nothing, and that a read-only session is therefore allowed to make. */
const READ_METHODS = new Set(['GET', 'HEAD']);

export function writePermissions(matrix) {
  const writes = new Set();
  for (const endpoint of matrix.endpoints ?? [])
    if (endpoint.permission && !READ_METHODS.has(String(endpoint.method).toUpperCase()))
      writes.add(endpoint.permission);
  return [...writes].sort();
}

export function render(keys) {
  return `/**
 * Generated by \`pnpm gen:permissions\` from server/src/main/resources/permissions.json.
 * Do not edit: \`permissions.generated.spec.ts\` re-derives it and fails on drift.
 *
 * A permission is a **write** when at least one endpoint declaring it uses a method other than
 * GET or HEAD — which is exactly what a read-only "View as" session is refused.
 */
export const WRITE_PERMISSIONS: ReadonlySet<string> = new Set([
${keys.map((key) => `  '${key}',`).join('\n')}
]);
`;
}

// Running as a script rather than being imported by the spec.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const matrix = JSON.parse(readFileSync(SOURCE, 'utf8'));
  const next = render(writePermissions(matrix));

  if (process.argv.includes('--check')) {
    const current = readFileSync(TARGET, 'utf8');
    if (current !== next) {
      process.stderr.write(
        'gen:permissions — permissions.generated.ts is stale. Run `pnpm gen:permissions`.\n',
      );
      process.exit(1);
    }
    process.stdout.write('gen:permissions — up to date\n');
  } else {
    writeFileSync(TARGET, next);
    process.stdout.write(`gen:permissions — ${writePermissions(matrix).length} write permissions\n`);
  }
}
